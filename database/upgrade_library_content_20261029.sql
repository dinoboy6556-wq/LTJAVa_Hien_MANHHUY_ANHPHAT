USE library_db;
CREATE TABLE IF NOT EXISTS library_content (
id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
kind VARCHAR(20) NOT NULL,title VARCHAR(255) NOT NULL,slug VARCHAR(120) NOT NULL UNIQUE,
body LONGTEXT,link VARCHAR(500),book_id BIGINT,published BIT NOT NULL DEFAULT 0,sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
